const kebab = (s: string): string => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/** `palette.primary.500` -> `--color-primary-500`, `color.bg` -> `--color-bg`, `font.lineHeight.lg` -> `--font-line-height-lg`. */
export function cssVar(path: string): string {
  const parts = path.split('.');
  if (parts[0] === 'palette') parts[0] = 'color';
  return `--${parts.map(kebab).join('-')}`;
}

/**
 * Tailwind v4 theme variable for a token, following Tailwind's namespaces so utilities are generated
 * (`--text-lg`, `--text-lg--letter-spacing`, `--font-sans`, `--spacing-gap`, ...). Returns null for tokens Tailwind derives itself:
 * the numeric spacing steps all come from the single `--spacing` unit.
 */
export function tailwindVar(path: string): string | null {
  const p = path.split('.');
  if (p[0] === 'font') {
    if (p[1] === 'family') return `--font-${p[2]}`;
    if (p[1] === 'size') return `--text-${p[2]}`;
    if (p[1] === 'lineHeight') return `--text-${p[2]}--line-height`;
    if (p[1] === 'tracking') return `--text-${p[2]}--letter-spacing`;
    if (p[1] === 'weight') return `--font-weight-${p[2]}`;
  }
  if (p[0] === 'space') return /^\d+$/.test(p[1]!) ? null : `--spacing-${p[1]}`;
  return cssVar(path);
}

/**
 * First line of every emitted file. The name lands inside CSS, HTML, SCSS and TS comments, so anything
 * that could close a comment or start markup is dropped rather than escaped per format.
 */
export const HEADER = (name: string): string =>
  `Generated by Kaava for "${name.replace(/[^\p{L}\p{N} ._-]/gu, '').trim()}". Do not edit by hand: change kaava.json through the Kaava MCP tools and re-emit.`;
