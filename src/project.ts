import { mkdir, readFile, realpath, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { KaavaSystem } from './engine/resolve.js';
import { systemFileSchema } from './schema.js';

export const SYSTEM_FILE = 'kaava.json';

export const isInside = (root: string, target: string): boolean => {
  const rel = path.relative(root, target);
  return rel === '' || (!rel.startsWith('..') && !path.isAbsolute(rel));
};

/** Resolve a project-relative path, refusing anything that would land outside the project root. */
export function resolveInside(root: string, relative: string): string {
  const target = path.resolve(root, relative);
  if (!isInside(root, target)) {
    throw new Error(`"${relative}" resolves outside the project root (${root}). Kaava only writes inside the project.`);
  }
  return target;
}

export async function readSystem(root: string): Promise<KaavaSystem | undefined> {
  const file = path.join(root, SYSTEM_FILE);
  let raw: string;
  try {
    raw = await readFile(file, 'utf8');
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
    throw err;
  }
  let json: unknown;
  try {
    json = JSON.parse(raw);
  } catch (err) {
    throw new Error(`${file} is not valid JSON: ${(err as Error).message}`);
  }
  const parsed = systemFileSchema.safeParse(json);
  if (!parsed.success) {
    const issue = parsed.error.issues[0];
    throw new Error(`${file} is not a valid Kaava system: ${issue?.path.join('.') || '(root)'}: ${issue?.message}`);
  }
  return parsed.data as unknown as KaavaSystem;
}

export async function loadSystem(root: string): Promise<KaavaSystem> {
  const system = await readSystem(root);
  if (!system) {
    throw new Error(`No ${SYSTEM_FILE} in ${root}. Create a design system first with kaava_create_system.`);
  }
  return system;
}

export const serializeSystem = (system: KaavaSystem): string => `${JSON.stringify(system, null, 2)}\n`;

/** Present in every file Kaava emits; used to tell generated files from hand-written ones. */
export const GENERATED_MARKER = 'Generated by Kaava';

const isMissing = (err: unknown): boolean => (err as NodeJS.ErrnoException).code === 'ENOENT';

/**
 * Resolve a project-relative path for writing. Beyond the lexical check, symlinks are followed on the
 * part of the path that already exists, so a link inside the project cannot redirect a write outside it.
 */
export async function resolveForWrite(root: string, relative: string): Promise<string> {
  const target = resolveInside(root, relative);
  let realRoot: string;
  try {
    realRoot = await realpath(root);
  } catch (err) {
    if (isMissing(err)) throw new Error(`Project root ${root} does not exist.`);
    throw err;
  }
  for (let probe = target; ; probe = path.dirname(probe)) {
    try {
      if (!isInside(realRoot, await realpath(probe))) {
        throw new Error(`"${relative}" leads outside the project root through a symlink. Kaava only writes inside the project.`);
      }
      return target;
    } catch (err) {
      if (!isMissing(err) || path.dirname(probe) === probe) throw err;
    }
  }
}

/** True when the file exists and was not generated by Kaava, i.e. overwriting it would destroy someone's work. */
export async function isForeignFile(file: string): Promise<boolean> {
  try {
    return !(await readFile(file, 'utf8')).includes(GENERATED_MARKER);
  } catch (err) {
    if (isMissing(err)) return false;
    throw err;
  }
}

/** Write via a temp file and rename, so a crash never leaves a half-written file behind. */
export async function writeProjectFile(root: string, relative: string, content: string): Promise<string> {
  const target = await resolveForWrite(root, relative);
  await mkdir(path.dirname(target), { recursive: true });
  const temp = `${target}.${process.pid}.tmp`;
  await writeFile(temp, content, 'utf8');
  await rename(temp, target);
  return target;
}
