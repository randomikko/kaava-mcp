// Rewrites styles/index.ts from the JSON files in styles/. Run with `npm run styles` after adding or removing a style.
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'styles');

export function stylesIndex(ids) {
  const sorted = [...ids].sort();
  const ident = (id) => (id === 'default' ? 'defaultStyle' : id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^(\d)/, '_$1'));
  const others = sorted.filter((id) => id !== 'default');
  return [
    '// Generated by scripts/styles-index.mjs from the JSON files in this folder. Do not edit by hand.',
    ...sorted.map((id) => `import ${ident(id)} from './${id}.json' with { type: 'json' };`),
    '',
    '/** Every built-in style, as authored. `default` comes first. */',
    `export const STYLE_FILES: unknown[] = [${['default', ...others].map(ident).join(', ')}];`,
    '/** Ids of the built-in styles other than `default`, which is what a brief gets when it names no style. */',
    `export const STYLE_IDS = [${others.map((id) => `'${id}'`).join(', ')}] as const;`,
    '',
  ].join('\n');
}

export const styleIds = () => readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5));

export function writeStylesIndex() {
  writeFileSync(path.join(dir, 'index.ts'), stylesIndex(styleIds()));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeStylesIndex();
  console.log(`styles/index.ts: ${styleIds().length} styles`);
}
